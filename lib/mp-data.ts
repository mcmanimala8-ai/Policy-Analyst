export function getPartyBreakdown() {
  const counts: Record<string, number> = {}
  MPs.forEach((mp) => {
    counts[mp.party] = (counts[mp.party] || 0) + 1
  })
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([party, count]) => ({ party, count }))
}
